"""design.json -> the Markdown schematic document (the "Schematic MD" format the studio's importer also reads:
title, summary, datasheet citations, BOM table, one pin block per part, net summary).

The MD is generated by code from the design, never typed by the AI, so it can't drift from the schematic:
the studio rewrites it after every change (AI edits, BOM edits, LCSC numbers, re-imports from Eagle).
The AI only supplies the prose parts it knows: title, subtitle, summary bullets, datasheet citations and
which section a part belongs to (set_doc tool).

Pin numbers in the MD are the physical pads from the library; the name in brackets is the library pin name.
"""
from __future__ import annotations

import hashlib
import re
from typing import Dict, List, Optional, Tuple

PASSIVE = ("R", "C", "L")
LINE = "───"
SUPPLY_RE = re.compile(r"^(GND|AGND|DGND|PGND|VSS|VDD|VCC|VIN|VBAT|VBUS|\+?\d+V\d*|V\d+V\d*|VCC\d*V?\d*|3V3|5V|12V)", re.I)


def _prefix(ref: str) -> str:
    return re.sub(r"\d.*", "", ref.upper())


def _sort_key(ref: str):
    return (_prefix(ref), int("0" + "".join(c for c in ref if c.isdigit())))


def _pad_tok(ref: str, pad: str) -> str:
    return f"{ref}.Pin{pad}" if pad.isdigit() else f"{ref}.{pad}"


_ASCII_MAP = {"–": "-", "—": "-", "→": "->", "←": "<-", "±": "+/-", "°": " deg", "×": "x", "≤": "<=", "≥": ">=",
              "“": '"', "”": '"', "‘": "'", "’": "'", "…": "...", "μ": "µ", "•": "-", "\u00a0": " "}


def _ascii(text: str) -> str:
    """The format allows only ASCII plus ─, Ω and µ."""
    out = []
    for ch in text:
        if ord(ch) < 128 or ch in "─Ωµ":
            out.append(ch)
        else:
            out.append(_ASCII_MAP.get(ch, "?" if ch.isprintable() else " "))
    return "".join(out)


def _clean(s: str) -> str:
    return _ascii(re.sub(r"<[^>]+>", " ", s or "").replace("|", "/").replace("\n", " ")).strip()


_FAMILIES = ("TSSOP", "MSOP", "SSOP", "SOIC", "SOP", "SOT", "SOD", "QFN", "DFN", "TQFP", "LQFP", "QFP", "DIP",
             "PDIP", "TO", "SC", "LFCSP", "WSON", "PLCC", "BGA", "LGA")


def package_token(pkg: str) -> str:
    """Library package name -> the footprint token the format uses (0603, SOT-23-5, SOIC-8, DO-214AA...)."""
    p = (pkg or "").upper().replace("_", "-")
    m = re.search(r"(?<!\d)(0201|0402|0603|0805|1206|1210|1812|2010|2512)(?!\d)", p)
    if m and re.match(r"^[RCL]?(-?\w+-)?\d{4}", p):
        return m.group(1)
    m = re.search(r"DO-?(214A[ABC]|41|35|15|201)", p)
    if m:
        return "DO-" + m.group(1)
    if re.search(r"DPAK|TO-?252", p):
        return "DPAK"
    for fam in _FAMILIES:
        m = re.match(rf"^{fam}-?(\d+[A-Z]?)(?:-(\d+))?", p)
        if m:
            return f"{fam}-{m.group(1)}" + (f"-{m.group(2)}" if m.group(2) else "")
    return _clean(pkg) or "-"


CLASS_WORDS = {"U": "IC", "Q": "transistor / MOSFET", "D": "diode", "LED": "LED", "J": "connector", "P": "connector",
               "X": "connector", "F": "fuse", "K": "relay", "Y": "crystal", "SW": "switch", "S": "switch",
               "TP": "test point", "FB": "ferrite bead", "T": "transformer", "BT": "battery", "M": "module"}


def _value_text(ps) -> str:
    v = (ps.value or "").strip()
    pre = _prefix(ps.ref)
    if pre == "R" and v and not re.search(r"[ΩR]$|ohm", v, re.I):
        v += "Ω"
    if pre == "C" and v and not v.upper().endswith("F"):
        v += "F"
    if pre == "L" and v and not v.upper().endswith("H"):
        v += "H"
    return v.replace("u", "µ") if pre in PASSIVE and re.match(r"^[\d.]+u", v) else v


def _description(ps, dev) -> str:
    pre = _prefix(ps.ref)
    if pre == "C":
        name = f"{ps.deviceset} {ps.device} {dev.description if dev else ''}".upper()
        kind = "Electrolytic" if any(k in name for k in ("CPOL", "POLAR", "ELKO", "ELECTROLYT", "TANT")) else "Ceramic"
        return f"{_value_text(ps)} {kind}".strip()
    if pre == "R":
        return f"{_value_text(ps)} resistor".strip()
    if pre == "L":
        return f"{_value_text(ps)} inductor".strip()
    if ps.note:
        return _clean(ps.note)[:60]
    d = _clean(dev.description if dev else "")
    d = re.sub(r"GENERATED .*?(USE|$)", "", d, flags=re.I)        # builder's verify-note is not a description
    d = re.sub(r"\s+", " ", d).strip(" .-")
    cls = CLASS_WORDS.get(pre, "")
    if d and cls and cls.split()[0].lower() not in d.lower():
        d = f"{d} ({cls})"
    return (d[:70] or (f"{ps.deviceset} {cls}".strip()))


def _pins_of(design, index, ref) -> Tuple[Optional[object], List[Tuple[str, str, List[str]]]]:
    """[(pad, pin name, [nets])] for every pad of the part, in pad order."""
    dev, _err = design.device_for(index, ref)
    if dev is None:
        return None, []
    pad_net: Dict[str, List[str]] = {}
    for net, members in design.nets.items():
        for m in members:
            r, p = m.split(".", 1)
            if r.upper() != ref:
                continue
            found, _e = dev.resolve(p)
            for pin in found:
                for pad in pin.pads:
                    pad_net.setdefault(pad, [])
                    if net not in pad_net[pad]:
                        pad_net[pad].append(net)
    rows = []
    for pin in dev.pins:
        for pad in pin.pads:
            rows.append((pad, pin.name, pad_net.get(pad, [])))
    rows.sort(key=lambda r: (0, int(r[0])) if r[0].isdigit() else (1, r[0]))
    return dev, rows


def _members(design, index, net) -> List[Tuple[str, str, str]]:
    """[(ref, pad, pin name)] of a net, resolved to physical pads."""
    out = []
    for m in design.nets.get(net, []):
        r, p = m.split(".", 1)
        r = r.upper()
        dev, _ = design.device_for(index, r)
        if dev is None:
            out.append((r, p, p))
            continue
        found, _e = dev.resolve(p)
        if not found:
            out.append((r, p, p))
        for pin in found:
            for pad in pin.pads:
                out.append((r, pad, pin.name))
    seen, uniq = set(), []
    for t in out:
        if (t[0], t[1]) not in seen:
            seen.add((t[0], t[1]))
            uniq.append(t)
    return uniq


def _ordered_members(design, index, net):
    """Net members with the 'owner' first: ICs/active parts before connectors before passives."""
    mem = _members(design, index, net)
    rank = lambda t: (2 if _prefix(t[0]) in PASSIVE else 1 if _prefix(t[0]) in ("J", "P", "X", "CN") else 0,
                      _sort_key(t[0]), int(t[1]) if t[1].isdigit() else 0)
    return sorted(mem, key=rank)


def _tok(r, pd, nm, with_name=True):
    return _pad_tok(r, pd) + (f" ({_ascii(nm)})" if with_name and pd.isdigit() and nm != pd else "")


def write_md(design, index, version: str = "", stamp: str = "") -> str:
    """The Markdown schematic in the Schematic MD format:
    title + subtitle, summary bullets, ## Datasheet Citations, ## COMPLETE BILL OF MATERIALS (Ref | Qty | Part Number |
    Value | Description | Package ...), ## SECTION n blocks with ### REF - Description and a fenced pin block
    ('Pin N (name): Net X ─── Other.PinM', one target per line, consistent both ways), and Net summary lines."""
    from .ratings import analyze, group_text, net_voltage
    doc = getattr(design, "doc", None) or {}
    parts = sorted(design.parts.values(), key=lambda p: _sort_key(p.ref))
    ratings = analyze(design, index)
    L: List[str] = [f"# {_ascii(doc.get('title') or design.name)}", ""]
    L.append(_ascii(doc.get("subtitle") or "Schematic specification"))
    L.append("")
    L.append(f"> Created with Eagle AI Design Studio{(' v' + version) if version else ''} - generated from the "
             f"project's design.json and kept in sync with it" + (f" (last updated {stamp})" if stamp else "") + ".")
    L.append("")
    supplies = sorted(n for n in design.nets if SUPPLY_RE.match(n))
    bullets = [_ascii(b) for b in (doc.get("summary") or [])]
    bullets += [f"Part count: {len(parts)}" + (f" ({sum(1 for p in parts if p.dnp)} DNP)" if any(p.dnp for p in parts) else ""),
                f"Nets: {len(design.nets)}"]
    if supplies:
        bullets.append("Power: supply nets " + ", ".join(supplies))
    volts = []
    for n in sorted(design.nets, key=lambda x: (not SUPPLY_RE.match(x), x)):
        v, src = net_voltage(design, n)
        if v and (src == "set" or SUPPLY_RE.match(n)):
            volts.append(f"{n} {v:g} V" + ("" if src == "set" else " (from the name)"))
    if volts:
        bullets.append("Net voltages (worst case, used for the ratings): " + ", ".join(volts))
    L += [f"- {b}" for b in bullets] + [""]

    # Datasheet Citations (immediately after the summary)
    L += ["## Datasheet Citations", ""]
    cites = doc.get("citations") or {}
    active = [p for p in parts if _prefix(p.ref) not in PASSIVE]
    used = set()
    for p in active:
        c = cites.get(p.ref) or cites.get(p.mpn) or ""
        used |= {p.ref, p.mpn}
        L.append(f"- {p.ref} {_ascii(p.mpn or p.deviceset)}: " + (_ascii(c) if c else
                 f"no datasheet recorded - pin numbers/names from the Eagle library part {p.library}/{p.deviceset}"))
    for k, c in cites.items():
        if k not in used:
            L.append(f"- {_ascii(k)}: {_ascii(c)}")
    if not active and not cites:
        L.append("- No ICs or active parts in this design.")
    L.append("")

    # COMPLETE BILL OF MATERIALS
    L += ["## COMPLETE BILL OF MATERIALS", "",
          "| Ref | Qty | Part Number | Value | Description | Package | Rating (min) | LCSC | Note |",
          "|-----|-----|-------------|-------|-------------|---------|--------------|------|------|"]
    for g in sorted(design.bom(), key=lambda g: _sort_key(g["refs"].split(",")[0].strip())):
        refs = [r.strip() for r in g["refs"].split(",")]
        ps = design.parts[refs[0]]
        dev, _ = design.device_for(index, ps.ref)
        passive = _prefix(ps.ref) in PASSIVE
        pn = ps.mpn or ("Generic" if passive else ps.deviceset)
        value = _value_text(ps) if passive else (ps.value or ps.mpn or ps.deviceset)
        note = ("DNP. " if ps.dnp else "") + _clean(ps.note)
        L.append(f"| {', '.join(refs)} | {len(refs)} | {_clean(pn)} | {_clean(value)} | {_description(ps, dev)} | "
                 f"{package_token(dev.package if dev else '')} | {_clean(group_text(ratings, refs, True))} | "
                 f"{ps.lcsc or ''} | {note} |")
    L.append("")

    # component sections
    sec_of = {k.upper(): v for k, v in (doc.get("sections") or {}).items()}

    def default_section(ref):
        pre = _prefix(ref)
        return ("Connectors" if pre in ("J", "P", "X", "CN", "TP")
                else "Passive components" if pre in PASSIVE else "ICs and active components")
    order: List[str] = []
    groups: Dict[str, List] = {}
    for p in parts:
        sname = sec_of.get(p.ref) or default_section(p.ref)
        if sname not in groups:
            order.append(sname)
        groups.setdefault(sname, []).append(p)
    defaults = ["ICs and active components", "Connectors", "Passive components"]
    first_seen = {x: i for i, x in enumerate(order)}
    order.sort(key=lambda x: (defaults.index(x) + 1000) if x in defaults else first_seen[x])

    # one owner per connection: every member points at the net's first member; the first member points at the 2nd
    target_of: Dict[Tuple[str, str, str], Tuple[str, str, str]] = {}
    for net in design.nets:
        mem = _ordered_members(design, index, net)
        for i, t in enumerate(mem):
            if len(mem) > 1:
                target_of[(net, t[0], t[1])] = mem[1] if i == 0 else mem[0]

    n = 0
    for sname in order:
        n += 1
        L += [f"## SECTION {n}: {_ascii(sname)}", ""]
        for p in sorted(groups[sname], key=lambda q: (_prefix(q.ref) in PASSIVE, _sort_key(q.ref))):
            dev, rows = _pins_of(design, index, p.ref)
            passive = _prefix(p.ref) in PASSIVE
            head = _value_text(p) if passive else f"{_ascii(p.mpn or p.value or p.deviceset)} {_description(p, dev)}"
            L.append(f"### {p.ref} - {head}".rstrip())
            L.append("```")
            if dev is None:
                L.append(f"Library part {p.library}/{p.deviceset}/{p.device} not found - pins unknown")
            named_pins = not passive and _prefix(p.ref) not in ("D", "LED")
            for pad, name, nets in rows:
                if pad.isdigit():
                    src = f"Pin {pad}" + (f" ({_ascii(name)})" if (named_pins or name != pad) else "")
                else:
                    src = _ascii(pad)
                if not nets:
                    L.append(f"{src}: Not connected" if named_pins or not pad.isdigit() else f"{src}: Not connected")
                    continue
                for net in nets:
                    t = target_of.get((net, p.ref, pad))
                    L.append(f"{src}: Net {net}" + (f" {LINE} {_tok(*t)}" if t else " (no other connection)"))
            L.append("```")
            rt = ratings.get(p.ref)
            if rt is not None and (rt.need or rt.problems or (rt.missing and passive)):
                L.append(f"Rating: {_ascii(rt.detail())}")
            L.append("")

    # Net summary - the authoritative roster
    n += 1
    L += [f"## SECTION {n}: Net Summary", "", "```"]
    for net in sorted(design.nets, key=lambda x: (not SUPPLY_RE.match(x), x)):
        L.append(f"Net {net}: " + ", ".join(_tok(*t) for t in _ordered_members(design, index, net)))
    L += ["```", ""]
    return "\n".join(L)


# ------------------------------------------------------------------ adopting an older MD
def extract_doc(text: str) -> Dict:
    """Prose from an existing MD (AI-written or older studio file): title, subtitle, summary bullets, datasheet
    citations and which ### part sits under which ## SECTION. Parts/nets are NOT taken from here (the importer does
    that); this only keeps the human parts of the document when the studio starts rewriting it."""
    doc: Dict = {}
    lines = text.splitlines()
    i = 0
    while i < len(lines) and not lines[i].startswith("# "):
        i += 1
    if i < len(lines):
        doc["title"] = lines[i][2:].strip()
        i += 1
    summary, cites, sections = [], {}, {}
    sub = None
    sec = None
    in_cite = False
    for l in lines[i:]:
        st = l.strip()
        if st.startswith("## "):
            in_cite = "DATASHEET CITATION" in st.upper()
            m = re.match(r"##\s+SECTION\s+\d+\s*:\s*(.+)$", st, re.I)
            sec = m.group(1).strip() if m else None
            if sec and sec.lower().startswith("net summary"):
                sec = None
            continue
        if st.startswith(">") and "Eagle AI Design Studio" in st:
            continue
        if not doc.get("_body") and sub is None and st and not st.startswith(("-", "*", "#", "|", ">", "`")):
            sub = st
            continue
        if not doc.get("_body") and st.startswith(("- ", "* ")) and not cites and sec is None and not in_cite:
            b = st[2:].strip()
            if not re.match(r"^(Part count|Parts|Nets|Power: supply nets|Supply nets|This file is written|"
                            r"Net voltages \(worst case)", b):
                summary.append(b)
            continue
        if in_cite and st.startswith(("- ", "* ")):
            m = re.match(r"^[-*]\s+([A-Z]{1,4}\d{1,4}[A-Z]?)\b\s*([^:]*):\s*(.+)$", st)
            if m and not m.group(3).startswith("no datasheet recorded"):
                cites[m.group(1)] = m.group(3).strip()
            else:
                m = re.match(r"^[-*]\s+([^:]+):\s*(.+)$", st)
                if m and not m.group(2).startswith("no datasheet recorded"):
                    cites[m.group(1).strip()] = m.group(2).strip()
            continue
        h = re.match(r"^###\s+([A-Z]{1,4}\d{1,4}[A-Z]?)\b", st)
        if h:
            doc["_body"] = True
            if sec:
                sections[h.group(1)] = sec
        if st.startswith("## ") or st.startswith("|"):
            doc["_body"] = True
    doc.pop("_body", None)
    if sub:
        doc["subtitle"] = sub
    if summary:
        doc["summary"] = summary
    if cites:
        doc["citations"] = cites
    if sections:
        doc["sections"] = sections
    return doc


def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]
